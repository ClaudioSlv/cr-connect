begin;
do $$
declare fixture record; staff uuid; customer uuid; bid uuid; oid uuid; line uuid; details jsonb; revision uuid; rejected boolean;
begin
  select c.workshop_id,c.id as client_id,v.id as vehicle_id,l.user_id as customer into fixture from public.clients c join public.client_portal_links l on l.client_id=c.id join public.vehicles v on v.client_id=c.id where not exists (select 1 from public.workshop_users w where w.user_id=l.user_id and w.workshop_id=c.workshop_id) limit 1;
  select user_id into staff from public.workshop_users where workshop_id=fixture.workshop_id limit 1;
  select user_id into customer from public.client_portal_links where client_id=fixture.client_id limit 1;
  perform set_config('request.jwt.claim.sub',staff::text,true);
  insert into public.budgets(workshop_id,client_id,vehicle_id,status) values(fixture.workshop_id,fixture.client_id,fixture.vehicle_id,'draft') returning id into bid;
  insert into public.budget_items(workshop_id,budget_id,kind,description,quantity,unit_price,discount) values(fixture.workshop_id,bid,'service','Teste transacional de pagamento',1,700,0) returning id into line;
  details=public.get_document_payment_terms('budget',bid);
  details=public.save_document_payment_terms('budget',bid,'credit_card','Pagamento na entrega. Parcelamento no cartão.',14.3,(details->>'revision')::uuid,'Parcelamento combinado');
  assert (details->>'total')::numeric=800.10,'Total incorreto';
  rejected=false;
  begin perform public.save_document_payment_terms('budget',bid,'cash','Teste',-1,(details->>'revision')::uuid); exception when others then rejected=true; end;
  assert rejected,'Percentual negativo permitido';
  rejected=false;
  begin perform public.accept_document_payment_terms('budget',bid,(details->>'revision')::uuid,700); exception when others then rejected=true; end;
  assert rejected,'Valor divergente aceito';
  details=public.accept_document_payment_terms('budget',bid,(details->>'revision')::uuid,800.10);
  assert details->'acceptance'->>'source'='workshop_record','Origem incorreta';
  revision=(details->>'revision')::uuid;
  update public.budget_items set description='Item alterado com mesmo valor' where id=line;
  details=public.get_document_payment_terms('budget',bid);
  assert details->'acceptance'='null'::jsonb,'Aceite antigo mantido após mudar item';
  rejected=false;
  begin perform public.accept_document_payment_terms('budget',bid,revision,800.10); exception when others then rejected=true; end;
  assert rejected,'Revisão antiga aceita';
  assert (select count(*) from public.payment_acceptance_events where document_id=bid)=1,'Histórico anterior perdido';
  perform set_config('request.jwt.claim.sub',staff::text,true);
  update public.budgets set status='sent' where id=bid;
  perform set_config('request.jwt.claim.sub',fixture.customer::text,true);
  details=public.get_document_payment_terms('budget',bid);
  rejected=false;
  begin perform public.respond_to_budget_with_payment(bid,true,false,(details->>'revision')::uuid,800.10); exception when others then rejected=true; end;
  assert rejected,'Aprovação sem checkbox permitida';
  perform public.respond_to_budget_with_payment(bid,true,true,(details->>'revision')::uuid,800.10);
  details=public.get_document_payment_terms('budget',bid);
  assert details->'acceptance'->>'source'='client_portal','Aceite do cliente não registrado';
  assert (select status='approved' from public.budgets where id=bid),'Aprovação não concluída';
  perform set_config('request.jwt.claim.sub',staff::text,true);
  details=public.save_document_payment_terms('budget',bid,'cash','Novas condições',15,(details->>'revision')::uuid,'Novo acordo');
  assert details->'acceptance'='null'::jsonb,'Aceite mantido para condições alteradas';
  assert (select status='draft' from public.budgets where id=bid),'Orçamento alterado continuou aprovado';
  perform set_config('request.jwt.claim.sub',gen_random_uuid()::text,true);
  rejected=false;
  begin perform public.get_document_payment_terms('budget',bid); exception when others then rejected=true; end;
  assert rejected,'Terceiro conseguiu ler condições';
  perform set_config('request.jwt.claim.sub',staff::text,true);
  insert into public.service_orders(workshop_id,client_id,vehicle_id,status,customer_complaint) values(fixture.workshop_id,fixture.client_id,fixture.vehicle_id,'open','Teste transacional') returning id into oid;
  insert into public.service_order_items(workshop_id,service_order_id,kind,description,quantity,unit_price,discount) values(fixture.workshop_id,oid,'service','Teste',1,700,0);
  details=public.get_document_payment_terms('order',oid);
  details=public.save_document_payment_terms('order',oid,'cash','Pagamento na entrega.',14.3,(details->>'revision')::uuid,'Parcelamento combinado');
  rejected=false;
  begin update public.service_orders set status='repairing' where id=oid; exception when others then rejected=true; end;
  assert rejected,'Reparo iniciado sem aceite';
  details=public.accept_document_payment_terms('order',oid,(details->>'revision')::uuid,800.10);
  update public.service_orders set status='repairing' where id=oid;
  assert (select status='repairing' from public.service_orders where id=oid),'Reparo bloqueado após aceite';
end;
$$;
rollback;
